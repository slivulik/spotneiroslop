import type { Tokens } from "../types.ts";
import { CSS_PREFIX } from "./css.ts";

/**
 * Tailwind CSS v4 theme (CSS-first config). Import after `tailwindcss`:
 *   @import "tailwindcss";
 *   @import "@sonora/design-tokens/tokens.css";
 *   @import "@sonora/design-tokens/theme.css";
 * Values reference the runtime CSS variables so dynamic theming (artwork colours,
 * reduced motion) flows through Tailwind utilities too.
 */
export function generateTailwindTheme(t: Tokens): string {
  const v = (name: string): string => `var(--${CSS_PREFIX}-${name})`;
  const lines: string[] = [];
  // Reset Tailwind's default palette so only brand colours exist.
  lines.push("  --color-*: initial;");
  lines.push("  --color-transparent: transparent;");
  lines.push("  --color-current: currentColor;");
  for (const [group, entries] of Object.entries(t.color)) {
    for (const name of Object.keys(entries)) {
      const utility = name === "default" ? group : `${group}-${name}`;
      lines.push(`  --color-${utility}: ${v(`color-${group}-${name}`)};`);
    }
  }
  for (const role of Object.keys(t.font.family)) lines.push(`  --font-${role}: ${v(`font-${role}`)};`);
  for (const [name, s] of Object.entries(t.typography)) {
    lines.push(`  --text-${name}: ${v(`type-${name}-size`)};`);
    lines.push(`  --text-${name}--line-height: ${v(`type-${name}-line-height`)};`);
    lines.push(`  --text-${name}--font-weight: ${s.weight};`);
    lines.push(`  --text-${name}--letter-spacing: ${s.tracking}em;`);
  }
  lines.push("  --radius-*: initial;");
  for (const name of Object.keys(t.radius)) lines.push(`  --radius-${name}: ${v(`radius-${name}`)};`);
  lines.push("  --shadow-*: initial;");
  for (const name of Object.keys(t.shadow)) lines.push(`  --shadow-${name}: ${v(`shadow-${name}`)};`);
  for (const name of Object.keys(t.blur)) lines.push(`  --blur-${name}: ${v(`blur-${name}`)};`);
  for (const name of Object.keys(t.motion.easing)) lines.push(`  --ease-${name}: ${v(`ease-${name}`)};`);
  // Breakpoints must be literal values: Tailwind compiles them into @media queries.
  lines.push("  --breakpoint-*: initial;");
  for (const [name, px] of Object.entries(t.breakpoint)) lines.push(`  --breakpoint-${name}: ${px / 16}rem;`);
  return `/* Generated by @sonora/design-tokens from tokens.json. Do not edit by hand. */\n@theme {\n${lines.join("\n")}\n}\n`;
}
