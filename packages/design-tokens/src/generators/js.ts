import type { Tokens } from "../types.ts";

const HEADER = "// Generated by @sonora/design-tokens from tokens.json. Do not edit by hand.\n";

export function generateJs(t: Tokens): string {
  return `${HEADER}export const tokens = Object.freeze(${JSON.stringify(t, null, 2)});\nexport default tokens;\n`;
}

/** Literal-typed declaration, so consumers get autocompletion on token names and values. */
export function generateDts(t: Tokens): string {
  const literal = JSON.stringify(t, null, 2);
  return `${HEADER}export declare const tokens: DeepReadonly<${literal}>;\nexport default tokens;\n\ntype DeepReadonly<T> = { readonly [K in keyof T]: T[K] extends object ? DeepReadonly<T[K]> : T[K] };\n`;
}
