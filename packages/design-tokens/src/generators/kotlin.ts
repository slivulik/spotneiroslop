import { parseColor, toArgbHex } from "../color.ts";
import type { Tokens } from "../types.ts";

export const KOTLIN_PACKAGE = "com.sonora.core.designsystem.tokens";

/** "bg-base" → "BgBase", "2" → "X2" (Kotlin identifiers can't start with a digit). */
export function pascal(name: string): string {
  const id = name
    .split(/[-_.\s]+/)
    .filter(Boolean)
    .map((part) => part[0]!.toUpperCase() + part.slice(1))
    .join("");
  return /^\d/.test(id) ? `X${id}` : id;
}

const float = (n: number): string => {
  const s = String(n);
  return `${s.includes(".") || s.includes("e") ? s : `${s}.0`}f`;
};

export function generateKotlin(t: Tokens): string {
  const out: string[] = [];
  const obj = (name: string, body: string[]): void => {
    out.push(`    object ${name} {`);
    out.push(...body.map((l) => `        ${l}`));
    out.push("    }", "");
  };

  out.push(
    "// Generated by @sonora/design-tokens from tokens.json. Do not edit by hand.",
    `package ${KOTLIN_PACKAGE}`,
    "",
    "import androidx.compose.animation.core.CubicBezierEasing",
    "import androidx.compose.ui.graphics.Color",
    "import androidx.compose.ui.text.font.FontWeight",
    "import androidx.compose.ui.unit.Dp",
    "import androidx.compose.ui.unit.TextUnit",
    "import androidx.compose.ui.unit.dp",
    "import androidx.compose.ui.unit.em",
    "import androidx.compose.ui.unit.sp",
    "",
    "enum class FontRole { Display, Text, Mono }",
    "",
    "data class TypeToken(",
    "    val size: TextUnit,",
    "    val lineHeight: TextUnit,",
    "    val weight: FontWeight,",
    "    val tracking: TextUnit,",
    "    val role: FontRole,",
    ")",
    "",
    "/** Spring parameters in Compose units (stiffness, dampingRatio). */",
    "data class SpringToken(val stiffness: Float, val dampingRatio: Float)",
    "",
    "object SonoraTokens {",
    `    const val BRAND_NAME: String = ${JSON.stringify(t.brand.name)}`,
    "",
  );

  const colors: string[] = [];
  for (const [group, entries] of Object.entries(t.color)) {
    for (const [name, value] of Object.entries(entries)) {
      colors.push(`val ${pascal(`${group}-${name}`)}: Color = Color(${toArgbHex(parseColor(value))})`);
    }
  }
  obj("Colors", colors);

  obj(
    "Typography",
    Object.entries(t.typography).map(
      ([name, s]) =>
        `val ${pascal(name)}: TypeToken = TypeToken(${s.size}.sp, ${s.lineHeight}.sp, FontWeight(${s.weight}), ${float(s.tracking)}.em, FontRole.${pascal(s.family)})`,
    ),
  );
  obj("Space", Object.entries(t.space).map(([n, v]) => `val ${pascal(n)}: Dp = ${v}.dp`));
  obj("Radius", Object.entries(t.radius).map(([n, v]) => `val ${pascal(n)}: Dp = ${v}.dp`));
  obj("Blur", Object.entries(t.blur).map(([n, v]) => `val ${pascal(n)}: Dp = ${v}.dp`));
  obj("Duration", Object.entries(t.motion.duration).map(([n, v]) => `const val ${pascal(n).toUpperCase()}_MS: Int = ${v}`));
  obj(
    "Easing",
    Object.entries(t.motion.easing).map(
      ([n, c]) => `val ${pascal(n)}: CubicBezierEasing = CubicBezierEasing(${c.map(float).join(", ")})`,
    ),
  );
  // Compose springs take a damping *ratio*: ζ = c / (2·√(k·m)).
  obj(
    "Springs",
    Object.entries(t.motion.spring).map(([n, s]) => {
      const ratio = s.damping / (2 * Math.sqrt(s.stiffness * s.mass));
      const stiffness = s.stiffness / s.mass;
      return `val ${pascal(n)}: SpringToken = SpringToken(stiffness = ${float(Number(stiffness.toFixed(3)))}, dampingRatio = ${float(Number(ratio.toFixed(4)))})`;
    }),
  );
  obj("Breakpoint", Object.entries(t.breakpoint).map(([n, v]) => `val ${pascal(n)}: Dp = ${v}.dp`));
  obj("Layer", Object.entries(t.layer).map(([n, v]) => `const val ${pascal(n).toUpperCase()}: Float = ${float(v)}`));

  while (out.at(-1) === "") out.pop();
  out.push("}", "");
  return out.join("\n");
}
