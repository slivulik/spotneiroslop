import type { CubicBezier, Tokens } from "../types.ts";

export const CSS_PREFIX = "sonora";

const px = (n: number): string => (n === 0 ? "0" : `${n}px`);
const ms = (n: number): string => `${n}ms`;
export const cubicBezier = (c: CubicBezier): string => `cubic-bezier(${c.join(", ")})`;

/** All tokens as flat [name, value] pairs, without the `--sonora-` prefix. */
export function flattenTokens(t: Tokens): Array<[string, string]> {
  const out: Array<[string, string]> = [];
  for (const [group, entries] of Object.entries(t.color)) {
    for (const [name, value] of Object.entries(entries)) out.push([`color-${group}-${name}`, value]);
  }
  for (const [role, stack] of Object.entries(t.font.family)) out.push([`font-${role}`, stack]);
  for (const [name, weight] of Object.entries(t.font.weight)) out.push([`font-weight-${name}`, String(weight)]);
  for (const [name, s] of Object.entries(t.typography)) {
    out.push([`type-${name}-size`, px(s.size)]);
    out.push([`type-${name}-line-height`, px(s.lineHeight)]);
    out.push([`type-${name}-weight`, String(s.weight)]);
    out.push([`type-${name}-tracking`, `${s.tracking}em`]);
    out.push([`type-${name}-family`, `var(--${CSS_PREFIX}-font-${s.family})`]);
  }
  for (const [name, v] of Object.entries(t.space)) out.push([`space-${name}`, px(v)]);
  for (const [name, v] of Object.entries(t.radius)) out.push([`radius-${name}`, px(v)]);
  for (const [name, v] of Object.entries(t.opacity)) out.push([`opacity-${name}`, String(v)]);
  for (const [name, v] of Object.entries(t.border)) out.push([`border-${name}`, px(v)]);
  for (const [name, v] of Object.entries(t.shadow)) out.push([`shadow-${name}`, v]);
  for (const [name, v] of Object.entries(t.blur)) out.push([`blur-${name}`, px(v)]);
  for (const [name, v] of Object.entries(t.motion.duration)) out.push([`duration-${name}`, ms(v)]);
  for (const [name, v] of Object.entries(t.motion.easing)) out.push([`ease-${name}`, cubicBezier(v)]);
  for (const [name, v] of Object.entries(t.breakpoint)) out.push([`breakpoint-${name}`, px(v)]);
  for (const [name, v] of Object.entries(t.layer)) out.push([`layer-${name}`, String(v)]);
  return out;
}

const HEADER = "/* Generated by @sonora/design-tokens from tokens.json. Do not edit by hand. */\n";

export function generateCss(t: Tokens): string {
  const vars = flattenTokens(t)
    .map(([name, value]) => `  --${CSS_PREFIX}-${name}: ${value};`)
    .join("\n");
  const typeClasses = Object.keys(t.typography)
    .map(
      (name) =>
        `.${CSS_PREFIX}-type-${name} {\n` +
        `  font-family: var(--${CSS_PREFIX}-type-${name}-family);\n` +
        `  font-size: var(--${CSS_PREFIX}-type-${name}-size);\n` +
        `  line-height: var(--${CSS_PREFIX}-type-${name}-line-height);\n` +
        `  font-weight: var(--${CSS_PREFIX}-type-${name}-weight);\n` +
        `  letter-spacing: var(--${CSS_PREFIX}-type-${name}-tracking);\n` +
        `}`,
    )
    .join("\n\n");
  const reducedMotion =
    `@media (prefers-reduced-motion: reduce) {\n  :root {\n` +
    Object.keys(t.motion.duration)
      .map((name) => `    --${CSS_PREFIX}-duration-${name}: 0ms;`)
      .join("\n") +
    `\n  }\n}`;
  const themes = Object.entries(t.themes)
    .map(([theme, def]) => {
      const body = Object.entries(def.color)
        .flatMap(([group, entries]) => Object.entries(entries).map(([name, value]) => `  --${CSS_PREFIX}-color-${group}-${name}: ${value};`))
        .join("\n");
      return `[data-theme="${theme}"] {\n  color-scheme: ${theme};\n${body}\n}`;
    })
    .join("\n\n");
  return `${HEADER}:root {\n  color-scheme: dark;\n${vars}\n}\n\n${themes}\n\n${reducedMotion}\n\n${typeClasses}\n`;
}
